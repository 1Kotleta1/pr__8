def para(text, indent=True, bold_prefix=None):
    p = doc.add_paragraph(style='ГОСТ')
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if bold_prefix:
        p.add_run(bold_prefix)
    p.add_run(text)
    return p


def image(name, caption, width=16.5):
    w, h = Image.open(S + name).size
    width = min(width, 23.0 * w / h)  # чтобы рисунок с подписью помещался на страницу
    p = doc.add_paragraph(style='ГОСТ')
    p.paragraph_format.first_line_indent = Cm(0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(S + name, width=Cm(width))
    fig[0] += 1
    c = doc.add_paragraph(style='ГОСТ')
    c.paragraph_format.first_line_indent = Cm(0)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(f'Рисунок {fig[0]} – {caption}')
    r.font.size = Pt(12)


