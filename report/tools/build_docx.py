# 3. TaskSet vs SequentialTaskSet
para('3. Отличие TaskSet от SequentialTaskSet.')
para('TaskSet – набор задач, из которого Locust на каждой итерации выбирает задачу случайно. Вероятность '
     'выбора определяется весом в декораторе @task(n): задача с весом 5 выполняется в среднем в 5 раз '
     'чаще задачи с весом 1. TaskSet подходит для моделирования обычного пользователя, который '
     'хаотично переходит по страницам и чаще выполняет одни действия, чем другие.')
para('SequentialTaskSet – набор задач, которые выполняются строго в порядке объявления в классе, '
     'после последней задачи цикл начинается заново. Его используют, когда шаги зависят друг от друга: '
     'например, нельзя переименовать или удалить расчёт, который ещё не создан. Данные между шагами '
     'передаются через атрибуты экземпляра (self.calc_id, self.a, self.b).')
para('В работе использованы оба варианта: ViewerTasks (TaskSet) – пользователь, который просматривает '
     'историю, статистику и иногда выполняет расчёт; AnalystScenario (SequentialTaskSet) – аналитик, '
     'который проходит полный жизненный цикл расчёта от генерации матриц до удаления.')

